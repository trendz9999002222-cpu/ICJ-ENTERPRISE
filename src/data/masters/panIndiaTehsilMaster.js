export const PanIndiaTehsilMaster = {
  /**
   * Get tehsils list for a given district name
   */
  getTehsils(districtName = "") {
    if (!districtName) return [];
    
    // Direct match
    if (PAN_INDIA_TEHSILS[districtName]) {
      return PAN_INDIA_TEHSILS[districtName];
    }

    // Case-insensitive fuzzy match
    const lower = districtName.toLowerCase();
    const key = Object.keys(PAN_INDIA_TEHSILS).find((k) => k.toLowerCase().includes(lower) || lower.includes(k.toLowerCase()));
    
    if (key && PAN_INDIA_TEHSILS[key]) {
      return PAN_INDIA_TEHSILS[key];
    }

    // Default universal fallback tehsils for unlisted districts
    return [
      `Sadar Tehsil (सदर तहसील - ${districtName})`,
      `North Sub-Division (उत्तरी सब-डिवीज़न)`,
      `South Sub-Division (दक्षिणी सब-डिवीज़न)`,
      `East Sub-Division (पूर्वी सब-डिवीज़न)`,
      `West Sub-Division (पश्चिमी सब-डिवीज़न)`,
    ];
  },
};

export default PanIndiaTehsilMaster;
