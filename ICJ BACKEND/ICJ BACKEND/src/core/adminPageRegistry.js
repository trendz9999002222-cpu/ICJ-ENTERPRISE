/**
 * Get page entry by stable Page ID (e.g. "J1", "J7")
 * @param {string} id 
 * @returns {object|null}
 */
export function getPageById(id) {
  if (!id) return null;
  const cleanId = String(id).trim().toUpperCase();
  return ADMIN_PAGE_REGISTRY.find((p) => p.id === cleanId) || null;
}

/**
 * Get page entry by URL route or alias
 * @param {string} pathname 
 * @returns {object|null}
 */
export function getPageByRoute(pathname) {
  if (!pathname) return null;
  const cleanPath = String(pathname).toLowerCase().split("?")[0].split("#")[0];

  // Exact route match
  const exact = ADMIN_PAGE_REGISTRY.find((p) => p.route === cleanPath || (p.aliases && p.aliases.includes(cleanPath)));
  if (exact) return exact;

  // Prefix match (for sub-routes)
  const matched = ADMIN_PAGE_REGISTRY.find((p) => {
    if (cleanPath.startsWith(p.route) && p.route !== "/") return true;
    return p.aliases && p.aliases.some((alias) => cleanPath.startsWith(alias) && alias !== "/");
  });

  return matched || null;
}

/**
 * Get all registered Admin pages
 * @returns {Array}
 */
export function getAllAdminPages() {
  return ADMIN_PAGE_REGISTRY;
}

/**
 * Resolve query (J-ID, route, or name)
 * @param {string} query 
 * @returns {object|null}
 */
export function resolveAdminPage(query) {
  if (!query) return null;
  const str = String(query).trim();
  
  // Try ID
  const byId = getPageById(str);
  if (byId) return byId;

  // Try Route
  const byRoute = getPageByRoute(str);
  if (byRoute) return byRoute;

  // Try Name
  const lower = str.toLowerCase();
  return (
    ADMIN_PAGE_REGISTRY.find(
      (p) => p.name.toLowerCase().includes(lower) || (p.hindiName && p.hindiName.includes(str))
    ) || null
  );
}

// Attach to window object in browser for developer inspection
if (typeof window !== "undefined") {
  window.getICJPageRegistry = getAllAdminPages;
  window.resolveICJPage = resolveAdminPage;
}

export default ADMIN_PAGE_REGISTRY;
