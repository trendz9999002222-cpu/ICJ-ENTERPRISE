export const getRolePermissions = (roleCode) => {
    const normalized = normalizeRoleCode(roleCode);
    const configuredMap = mergeRolePermissionMap(
        ROLE_PERMISSION_MAP,
        readAuthorizationConfig().rolePermissions
    );
    return configuredMap[normalized] || configuredMap.member;
};

export const getRouteAccessMap = () =>
    mergeRouteAccessMap(ROUTE_ACCESS_MAP, readAuthorizationConfig().routeAccess);

export const hasPermission = (roleCode, permission) => {
    const permissions = getRolePermissions(roleCode);
    if (permissions.includes("*")) return true;
    return permissions.includes(permission);
};

export const enforcePermission = (roleCode, permission) => {
    if (roleCode && !hasPermission(roleCode, permission)) {
        throw new Error(`Permission Denied: Role '${roleCode}' lacks required permission '${permission}'.`);
    }
    return true;
};

export const hasOrganizationPermission = (organizationPermissions = [], permission = "") => {
    const scoped = Array.isArray(organizationPermissions) ? organizationPermissions : [];
    if (scoped.includes("organization.*")) return true;
    return scoped.includes(permission);
};

export const getAllPermissions = () => [...ALL_PERMISSIONS];
