const readAuthorizationConfig = () => {
    if (typeof window === "undefined") return {};
    try {
        const raw = window.localStorage.getItem("icj_settings");
        const parsed = raw ? JSON.parse(raw) : [];
        const root = Array.isArray(parsed) ? parsed[0] : parsed;
        const membership = root?.membership && typeof root.membership === "object" ? root.membership : {};
        const authorization = membership?.authorization && typeof membership.authorization === "object"
            ? membership.authorization
            : {};
        return authorization;
    } catch {
        return {};
    }
};

const mergeRolePermissionMap = (baseMap, configuredMap) => {
    const source = configuredMap && typeof configuredMap === "object" ? configuredMap : {};
    const merged = { ...baseMap };
    Object.entries(source).forEach(([roleCode, permissions]) => {
        if (Array.isArray(permissions)) {
            merged[String(roleCode).toLowerCase()] = permissions;
        }
    });
    return merged;
};

const mergeRouteAccessMap = (baseMap, configuredMap) => {
    const source = configuredMap && typeof configuredMap === "object" ? configuredMap : {};
    const merged = { ...baseMap };
    Object.entries(source).forEach(([roleCode, routes]) => {
        if (Array.isArray(routes)) {
            merged[String(roleCode).toLowerCase()] = routes;
        }
    });
    return merged;
};

